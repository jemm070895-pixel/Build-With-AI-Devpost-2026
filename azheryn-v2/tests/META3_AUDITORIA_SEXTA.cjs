const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const ui=fs.readFileSync(path.join(root,'src/ui/WorldView.tsx'),'utf8');
const work=fs.readFileSync(path.join(root,'src/world/work.ts'),'utf8');
assert.match(ui,/climateClock\.tick\(elapsed\)/);
assert.doesNotMatch(ui,/climateClock\.tick\(dt\)/);
assert.match(work,/const col = safeIndex % columns/);
const script=`import {createClimateClock} from ${JSON.stringify('file://'+path.join(root,'src/world/climate.ts'))};
const a=createClimateClock(10),b=createClimateClock(10),c=createClimateClock(10);
a.setSpeed(1);b.setSpeed(2);c.setSpeed(4);
a.tick(60);b.tick(60);c.tick(60);
const minutes=x=>{const v=x.snapshot();return (v.day-1)*1440+v.hour*60+v.minute};
const initial=8*60;
const d1=minutes(a)-initial,d2=minutes(b)-initial,d4=minutes(c)-initial;
if(d1!==60||d2!==120||d4!==240)throw Error('bad clock ratio '+[d1,d2,d4]);
const frozen=createClimateClock(10);frozen.setSpeed(0);frozen.tick(100);if(minutes(frozen)!==initial)throw Error('pause advances climate');
console.log('OK: climate x1/x2/x4 and pause runtime');`;
const result=spawnSync(process.execPath,['--experimental-strip-types','--input-type=module','-e',script],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
console.log(result.stdout.trim());
console.log('4/4 comprobaciones nuevas de auditoría sexta');
